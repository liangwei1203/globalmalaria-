# Project-relative directories
data_raw_dir       <- file.path("data", "raw")
data_processed_dir <- file.path("data", "processed")
data_example_dir   <- file.path("data", "example")
output_table_dir   <- file.path("outputs", "tables")
output_figure_dir  <- file.path("outputs", "figures")
output_model_dir   <- file.path("outputs", "models")

# Create output folders if they do not exist
invisible(lapply(
  c(data_raw_dir, data_processed_dir, data_example_dir,
    output_table_dir, output_figure_dir, output_model_dir),
  dir.create,
  recursive = TRUE,
  showWarnings = FALSE
))

# Helper: read input CSV.
# The function first checks data/processed and then data/raw.
# This allows downstream scripts to use imputed/processed files generated by earlier scripts.
input_file <- function(filename) {
  processed_path <- file.path(data_processed_dir, filename)
  raw_path <- file.path(data_raw_dir, filename)

  if (file.exists(processed_path)) return(processed_path)
  if (file.exists(raw_path)) return(raw_path)

  stop(
    "Input file not found: ", filename, "\n",
    "Please place it in either ", data_processed_dir, " or ", data_raw_dir, ".",
    call. = FALSE
  )
}

# Helper: write processed datasets generated by scripts.
processed_file <- function(filename) {
  file.path(data_processed_dir, filename)
}

# Helper: write result tables.
output_table_file <- function(filename) {
  file.path(output_table_dir, filename)
}

# Helper: write figures.
output_figure_file <- function(filename) {
  file.path(output_figure_dir, filename)
}

# Helper: write model objects or other intermediate outputs.
output_model_file <- function(filename) {
  file.path(output_model_dir, filename)
}

# Helper: package check without installing packages automatically.
require_package <- function(pkg) {
  if (!requireNamespace(pkg, quietly = TRUE)) {
    stop(
      "Required R package is not installed: ", pkg, "\n",
      "Please install it before running this script.",
      call. = FALSE
    )
  }
  suppressPackageStartupMessages(library(pkg, character.only = TRUE))
}

